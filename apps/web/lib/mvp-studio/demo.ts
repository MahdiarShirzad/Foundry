export function getMVPProject(id: string): MVPProject {
  return DEMO_MVP_PROJECTS.find((p) => p.id === id) ?? DEMO_MVP_PROJECTS[0];
}

export function getFeaturesForProject(
  features: Feature[],
  id: string,
): Feature[] {
  return features.filter((f) => f.projectId === id);
}

export function getScopeExtrasForProject(id: string): ScopeItem[] {
  return DEMO_SCOPE_EXTRAS.filter((s) => s.projectId === id);
}
